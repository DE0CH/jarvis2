// Writes ios/Shell/RadixColors.swift from @radix-ui/colors, so the shell's native secure sheets use the
// same colour steps as the React Native UI (src/theme/tokens.ts: accent blue, gray slate), light and dark.
const rc = require("@radix-ui/colors");
const fs = require("fs");
const scales = { gray: "slate", blue: "blue", red: "red", amber: "amber", green: "green" };
const hexa = (s) => {
  const m = s.match(/^#([0-9a-f]{6})([0-9a-f]{2})?$/i);
  if (!m) throw new Error("unexpected colour " + s);
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255, m[2] ? +(parseInt(m[2], 16) / 255).toFixed(4) : 1];
};
let out = "// GENERATED by scripts/gen-radix-swift.js from @radix-ui/colors: the app theme's colour steps, light + dark.\n"
  + "import SwiftUI\nimport UIKit\n\n"
  + "private func rgba(_ c: [Double]) -> UIColor { UIColor(red: c[0] / 255, green: c[1] / 255, blue: c[2] / 255, alpha: c[3]) }\n"
  + "private func dyn(_ l: [Double], _ d: [Double]) -> Color { Color(UIColor { $0.userInterfaceStyle == .dark ? rgba(d) : rgba(l) }) }\n\n"
  + "enum Radix {\n";
for (const [k, n] of Object.entries(scales)) {
  const L = rc[n], D = rc[n + "Dark"], LA = rc[n + "A"], DA = rc[n + "DarkA"];
  const step = (i) => `dyn([${hexa(L[n + i]).join(", ")}], [${hexa(D[n + i]).join(", ")}])`;
  const astep = (i) => `dyn([${hexa(LA[n + "A" + i]).join(", ")}], [${hexa(DA[n + "A" + i]).join(", ")}])`;
  const steps = (f) => [...Array(12).keys()].map((i) => "      " + f(i + 1)).join(",\n");
  out += `  enum ${k} {\n    static let s: [Color] = [.clear,\n${steps(step)}]\n    static let a: [Color] = [.clear,\n${steps(astep)}]\n  }\n`;
}
out += `  static let background = dyn([255, 255, 255, 1], [${hexa(rc.slateDark.slate1).join(", ")}])\n`
  + `  static let panel = dyn([255, 255, 255, 1], [${hexa(rc.slateDark.slate2).join(", ")}])\n`
  + "  static let surface = dyn([255, 255, 255, 0.85], [0, 0, 0, 0.25])\n"
  + "  static let overlay = dyn([0, 0, 0, 0.4], [0, 0, 0, 0.6])\n}\n";
fs.writeFileSync(__dirname + "/../ios/Shell/RadixColors.swift", out);
